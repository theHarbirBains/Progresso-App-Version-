// Maps Progresso's built-in exercises to the demonstration videos of the Free Exercise DB with
// Videos repository (github.com/harshvishu/free-exercise-db-with-videos), by Harbir's rules:
//
// - Only an exact name match counts (case and spacing aside) -- never a near name, an alias or a
//   similar movement. A built-in that doesn't match keeps no video; nothing of Progresso's is
//   renamed, merged or removed, and its id (and everything logged against it) stays as it is.
// - Where the repository has a male and a female demonstration, the male one; where it has only
//   one, that one. Which it is is never shown in the app.
// - One video per Progresso exercise: a name the repository lists twice gives one.
//
//   node tools/exercise-videos/map.mjs <path to the repository's data/exercises.json>
//
// Writes apps/mobile/src/exercises/videos/exerciseVideos.generated.ts (slug -> the video's file
// and take) and tools/exercise-videos/audit.generated.json (every repository exercise: matched,
// matched only by one of Progresso's other names, matched but for punctuation, or not at all), and
// prints the counts. The repository's file is read as data only.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const catalog = join(root, 'supabase', 'catalog');
const MODULES = ['dumbbell', 'barbell', 'bodyweight', 'cable', 'machine', 'smith', 'kettlebell', 'accessories'];

const source = process.argv[2];
if (!source) {
  console.error('Usage: node tools/exercise-videos/map.mjs <data/exercises.json>');
  process.exit(1);
}

const builtins = [];
for (const name of MODULES) {
  const mod = await import(new URL(`file:///${join(catalog, `${name}.mjs`).replace(/\\/g, '/')}`));
  builtins.push(...mod.default);
}

const repo = JSON.parse(readFileSync(source, 'utf8'));
if (!Array.isArray(repo)) throw new Error('Expected the repository data as a list of exercises.');

const exact = (text) => text.trim().replace(/\s+/g, ' ').toLowerCase();
const loose = (text) => text.toLowerCase().replace(/[^a-z0-9]/g, '');
const VIDEO = /\/exercise-videos\/(male|female)\/([a-z0-9-]+)\.mp4$/;

const byName = new Map(builtins.map((b) => [exact(b.name), b]));
const byAlias = new Map();
for (const b of builtins) for (const alias of b.aliases ?? []) byAlias.set(exact(alias), b);
const byLoose = new Map(builtins.map((b) => [loose(b.name), b]));

/** The take to use: the male demonstration where there is one, else the female. */
function chosenTake(entry) {
  const videos = entry.videos ?? {};
  const url = videos.male || videos.female;
  if (!url) return null;
  const found = VIDEO.exec(url);
  if (!found) throw new Error(`${entry.id}: an unexpected video address: ${url}`);
  return { take: found[1], file: found[2], both: Boolean(videos.male && videos.female) };
}

const videos = new Map();
const audit = { exact: [], aliasOnly: [], punctuationOnly: [], unmatched: [], repeated: [] };
for (const entry of repo) {
  const take = chosenTake(entry);
  const builtin = byName.get(exact(entry.name));
  if (builtin) {
    audit.exact.push({ id: entry.id, name: entry.name, slug: builtin.slug, ...take });
    const known = videos.get(builtin.slug);
    // A name listed twice: keep the male demonstration, else the first.
    if (known) {
      audit.repeated.push({ name: entry.name, slug: builtin.slug, kept: known.source });
      if (!(known.take !== 'male' && take?.take === 'male')) continue;
    }
    if (take) videos.set(builtin.slug, { file: take.file, take: take.take, source: entry.id });
    continue;
  }
  const alias = byAlias.get(exact(entry.name));
  if (alias) {
    audit.aliasOnly.push({ id: entry.id, name: entry.name, progresso: alias.name });
    continue;
  }
  const close = byLoose.get(loose(entry.name));
  if (close) {
    audit.punctuationOnly.push({ id: entry.id, name: entry.name, progresso: close.name });
    continue;
  }
  audit.unmatched.push({ id: entry.id, name: entry.name, equipment: entry.equipment, ...take });
}

const counts = {
  repository: repo.length,
  bothTakes: repo.filter((e) => e.videos?.male && e.videos?.female).length,
  maleOnly: repo.filter((e) => e.videos?.male && !e.videos?.female).length,
  femaleOnly: repo.filter((e) => !e.videos?.male && e.videos?.female).length,
  exactEntries: audit.exact.length,
  builtinsWithVideo: videos.size,
  aliasOnly: audit.aliasOnly.length,
  punctuationOnly: audit.punctuationOnly.length,
  unmatched: audit.unmatched.length,
  repeated: audit.repeated.length,
};

const sorted = [...videos.entries()].sort(([a], [b]) => a.localeCompare(b));
const ts = `// GENERATED by tools/exercise-videos/map.mjs -- do not edit by hand.
// Each built-in with a demonstration video in the Free Exercise DB with Videos repository, by an
// exact name match only: its video's file and which take it is (the male one where there are both,
// else the only one -- never shown in the app), and the repository's id for it. Where the file is
// served from is the video provider's (exerciseVideoSource.ts), so the provider can change without
// touching this.

export interface ExerciseVideoEntry {
  /** The video's file name, without its extension. */
  file: string;
  take: 'male' | 'female';
  /** The repository's id for the exercise. */
  source: string;
}

export const EXERCISE_VIDEOS: Readonly<Record<string, ExerciseVideoEntry>> = {
${sorted.map(([slug, v]) => `  '${slug}': { file: '${v.file}', take: '${v.take}', source: '${v.source}' },`).join('\n')}
};
`;
const out = join(root, 'apps', 'mobile', 'src', 'exercises', 'videos', 'exerciseVideos.generated.ts');
const config = await prettier.resolveConfig(out);
writeFileSync(out, await prettier.format(ts, { ...config, filepath: out }));
writeFileSync(
  join(here, 'audit.generated.json'),
  JSON.stringify({ counts, ...audit }, null, 2) + '\n',
);
console.log(JSON.stringify(counts, null, 2));
