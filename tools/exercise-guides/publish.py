"""Publishes the Exercise Guide's demonstration videos to the app: writes
apps/mobile/src/exercises/guide/exerciseDemos.generated.ts from demos.json and what's in
apps/mobile/assets/exercise-guides/<slug>/. The videos are Harbir's licensed videos -- only add
one whose licence covers showing it in the app.

    python tools/exercise-guides/publish.py

For each exercise in demos.json -- each must be an active built-in, listed once -- it looks for:

    demo.mp4        the demonstration (H.264; it plays muted, on a loop)
    demo.json       {"seconds": 18.0, "width": 1080, "height": 720, "audio": false}
    poster.webp     its first frame, shown while it loads
    step-1.webp ... a still for each step of Step-by-Step, in order
    equipment.webp  the machine alone, set up as the exercise uses it

Anything not there is null, never stood in for: the guide shows the exercise's own picture until
it has a video.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
ASSETS = os.path.join(ROOT, 'apps', 'mobile', 'assets', 'exercise-guides')
CATALOG = os.path.join(ROOT, 'apps', 'mobile', 'src', 'exercises', 'illustrations',
                       'builtinCatalog.generated.ts')
OUT = os.path.join(ROOT, 'apps', 'mobile', 'src', 'exercises', 'guide', 'exerciseDemos.generated.ts')
# From the generated file to the assets.
REL = '../../../assets/exercise-guides'

DEFAULT_ASPECT = 1.5


def builtin_slugs():
    text = open(CATALOG, encoding='utf-8').read()
    return set(re.findall(r"^  '([a-z0-9-]+)': \{", text, flags=re.M))


def asset(slug, name):
    return f"require('{REL}/{slug}/{name}')"


def demo_entry(slug, problems):
    folder = os.path.join(ASSETS, slug)
    has = (lambda name: os.path.isfile(os.path.join(folder, name)))
    meta = {}
    if has('demo.json'):
        meta = json.load(open(os.path.join(folder, 'demo.json'), encoding='utf-8'))
    video = has('demo.mp4')
    if video and not meta:
        problems.append(f'{slug}: demo.mp4 without demo.json (its length and size)')
        video = False

    steps = []
    n = 1
    while has(f'step-{n}.webp'):
        steps.append(asset(slug, f'step-{n}.webp'))
        n += 1

    aspect = DEFAULT_ASPECT
    if meta.get('width') and meta.get('height'):
        aspect = round(meta['width'] / meta['height'], 4)
    lines = [
        f"  '{slug}': {{",
        f"    video: {asset(slug, 'demo.mp4') if video else 'null'},",
        f"    poster: {asset(slug, 'poster.webp') if video and has('poster.webp') else 'null'},",
        f"    seconds: {round(float(meta['seconds']), 2) if video else 'null'},",
        f'    aspect: {aspect},',
        f"    audio: {'true' if video and meta.get('audio') else 'false'},",
        f"    steps: [{', '.join(steps)}],",
        f"    equipment: {asset(slug, 'equipment.webp') if has('equipment.webp') else 'null'},",
        '  },',
    ]
    return '\n'.join(lines)


def main():
    listed = json.load(open(os.path.join(HERE, 'demos.json'), encoding='utf-8'))['exercises']
    known = builtin_slugs()
    problems = []
    seen = set()
    for slug in listed:
        if slug in seen:
            problems.append(f'{slug}: listed twice')
        seen.add(slug)
        if slug not in known:
            problems.append(f'{slug}: not an active built-in')
    if problems:
        print('\n'.join(problems))
        sys.exit(1)

    entries = [demo_entry(slug, problems) for slug in listed]
    if problems:
        print('\n'.join(problems))
        sys.exit(1)

    body = '\n'.join(entries)
    text = f"""// GENERATED by tools/exercise-guides/publish.py -- do not edit by hand.
// The exercises whose guide is the Exercise Guide, and the demonstration each has.

export interface ExerciseDemo {{
  /** Its demonstration video (licensed), bundled -- null until it's added. */
  video: number | null;
  /** Its first frame, shown while it loads. */
  poster: number | null;
  /** How long one loop is, in seconds. */
  seconds: number | null;
  /** Width over height. */
  aspect: number;
  /** Whether it has a sound track: Sound is offered only then. */
  audio: boolean;
  /** A still for each step of Step-by-Step, in order (none until they're added). */
  steps: number[];
  /** The machine alone, set up as the exercise uses it. */
  equipment: number | null;
}}

export const EXERCISE_DEMOS: Record<string, ExerciseDemo> = {{
{body}
}};
"""
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'wrote {os.path.relpath(OUT, ROOT)} ({len(listed)} exercise{"" if len(listed) == 1 else "s"})')


if __name__ == '__main__':
    main()
