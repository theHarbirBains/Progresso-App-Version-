-- Micronutrients (explicitly requested): vitamins, minerals, fibre and the fats with no target,
-- tracked from the foods people log against Health Canada's Dietary Reference Intakes.
--
-- 1. Amounts. A food's amounts are kept like its other figures: foods.micronutrients per serving,
--    food_logs.micronutrients for the amount logged -- a snapshot made at logging time, never
--    worked out again from the food (CLAUDE.md's snapshot rule). Each is an object of nutrient id
--    to amount, in that nutrient's unit (nutrient_definitions.unit). A nutrient the food's source
--    didn't give is simply absent: never stored as 0, so "unknown" and "none" stay apart. Where an
--    amount came from is the row's existing provenance (nutrition_source_kind and the rest).
-- 2. USDA FoodData Central's reference foods keep theirs per 100 g, written by the importer.
-- 3. nutrient_definitions and nutrient_reference_values: what's tracked and Health Canada's values
--    for each life stage, filled by 20261214100100 (generated by supabase/nutrients/generate.mjs).
-- 4. fill_usda_micronutrients(): run by the importer after a release is loaded, it gives the
--    foods already cached from a USDA reference food -- and people's own unchanged copies of them
--    -- that food's amounts. Nothing else is filled in, and no log is ever changed.
--
-- Additive only: every existing figure, log and food stays exactly as it was.

-- Whether a micronutrient object is well formed: null, or nutrient ids to amounts of 0 or more.
create or replace function public.micronutrients_are_valid(p jsonb)
returns boolean
language sql
immutable
set search_path = public
as $$
  select p is null or (
    jsonb_typeof(p) = 'object'
    and not exists (
      select 1
      from jsonb_each(p) as e
      where e.key !~ '^[a-z][a-z0-9_]*$'
         or jsonb_typeof(e.value) <> 'number'
         or (e.value)::numeric < 0
    )
  );
$$;

alter table public.foods
  add column micronutrients jsonb
    constraint foods_micronutrients_valid check (public.micronutrients_are_valid(micronutrients));

alter table public.food_logs
  add column micronutrients jsonb
    constraint food_logs_micronutrients_valid
      check (public.micronutrients_are_valid(micronutrients));

alter table public.usda_food_reference
  add column micronutrients_per_100g jsonb
    constraint usda_food_reference_micronutrients_valid
      check (public.micronutrients_are_valid(micronutrients_per_100g));

comment on column public.foods.micronutrients is
  'Micronutrient amounts per serving, by nutrient id, in each nutrient''s unit. A nutrient the source did not give is absent, never 0.';
comment on column public.food_logs.micronutrients is
  'Micronutrient amounts for the amount logged, snapshotted at logging time. Null for logs made before micronutrients were tracked, or of a food with none known.';
comment on column public.usda_food_reference.micronutrients_per_100g is
  'Micronutrient amounts per 100 g from FoodData Central, in each nutrient''s unit. Absent where FoodData Central has no figure.';

-- 3. What's tracked, and Health Canada's values for it.
create table public.nutrient_definitions (
  id text primary key check (id ~ '^[a-z][a-z0-9_]*$'),
  name text not null,
  category text not null check (category in ('vitamin', 'mineral', 'other')),
  unit text not null check (unit in ('mcg', 'mg', 'g')),
  basis text,
  sort_order integer not null,
  -- Health Canada's guidance where it gives no number ("As low as possible ...").
  guidance text,
  dri_source_url text not null,
  dri_source_modified date not null
);

create table public.nutrient_reference_values (
  nutrient_id text not null references public.nutrient_definitions (id) on delete cascade,
  life_stage text not null
    check (life_stage in ('infants', 'children', 'males', 'females', 'pregnancy', 'lactation')),
  age_label text not null,
  -- The ages it covers, in months from birth: from age_min_months up to, not including, the max.
  age_min_months integer not null check (age_min_months >= 0),
  age_max_months integer check (age_max_months is null or age_max_months > age_min_months),
  reference_type text check (reference_type in ('RDA', 'AI')),
  reference_value numeric check (reference_value is null or reference_value > 0),
  ear numeric check (ear is null or ear > 0),
  -- Null where Health Canada set no upper limit ("ND"): none is ever assumed.
  ul numeric check (ul is null or ul > 0),
  cdrr numeric check (cdrr is null or cdrr > 0),
  -- Health Canada's own notes on these values, word for word.
  value_notes text[] not null default '{}',
  ul_notes text[] not null default '{}',
  primary key (nutrient_id, life_stage, age_min_months),
  check ((reference_type is null) = (reference_value is null))
);

alter table public.nutrient_definitions enable row level security;
alter table public.nutrient_reference_values enable row level security;
create policy nutrient_definitions_select on public.nutrient_definitions
  for select to authenticated using (true);
create policy nutrient_reference_values_select on public.nutrient_reference_values
  for select to authenticated using (true);
-- No insert, update or delete policies: only migrations write them.

-- 4. A USDA reference food's amounts onto the foods that are that food, scaled to their serving.
-- A food counts only while it's unchanged: its serving in grams, not a recipe, and its four
-- figures still the reference food's for that serving. One already holding amounts is left alone.
create or replace function public.fill_usda_micronutrients()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  update public.foods f
  set micronutrients = (
    select jsonb_object_agg(e.key, round((e.value)::numeric * f.serving_size / 100, 4))
    from jsonb_each(r.micronutrients_per_100g) as e
  )
  from public.usda_food_reference r
  where f.micronutrients is null
    and r.micronutrients_per_100g is not null
    and r.micronutrients_per_100g <> '{}'::jsonb
    and f.nutrition_source_kind = 'usda_fdc'
    and f.nutrition_source_id = r.fdc_id::text
    and f.recipe_servings is null
    and lower(f.serving_unit) = 'g'
    and abs(f.calories - r.calories_per_100g * f.serving_size / 100) < 0.5
    and abs(f.protein_g - r.protein_g_per_100g * f.serving_size / 100) < 0.05
    and abs(f.carbs_g - r.carbs_g_per_100g * f.serving_size / 100) < 0.05
    and abs(f.fat_g - r.fat_g_per_100g * f.serving_size / 100) < 0.05;
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

revoke all on function public.fill_usda_micronutrients() from public, anon, authenticated;
grant execute on function public.fill_usda_micronutrients() to service_role;
